"""Builds docs/importer_benchmark_report.md from results/*.json and acceptance.json.   python report.py"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent.parent


def load(name):
    return json.loads((HERE / "results" / name).read_text())


def passes(a: dict, acc: dict) -> tuple[bool, list[str]]:
    fails = []
    if a["cases"] < acc["min_heldout_cases"]:
        fails.append(f"only {a['cases']} held-out case(s)")
    for k in ("critical_accuracy", "recall", "statement_coverage", "period_accuracy", "unit_accuracy", "currency_accuracy"):
        if a[k] < acc[k]:
            fails.append(f"{k} {a[k]:.0%} < {acc[k]:.0%}")
    if a["confident_error_rate"] > acc["confident_error_rate"]:
        fails.append(f"confident errors {a['confident_error_rate']:.2%} > {acc['confident_error_rate']:.2%}")
    if a.get("wrong_caught_rate") is not None and a["wrong_caught_rate"] < acc["wrong_caught_rate"]:
        fails.append(f"wrong values caught {a['wrong_caught_rate']:.0%}")
    return not fails, fails


def table(rows, cols):
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def pct(x):
    return "n/a" if x is None else f"{x:.0%}"


def metrics_row(name, a):
    return [name, a["cases"], pct(a["extraction_success"]), pct(a["recall"]), pct(a["critical_accuracy"]), a["confident_errors"], f"{a['confident_error_rate']:.2%}", pct(a["statement_coverage"]),
            pct(a["period_accuracy"]), pct(a["unit_accuracy"]), pct(a["currency_accuracy"])]


COLS = ["", "cases", "extracted", "line recall", "critical lines", "confident errors", "rate", "statements", "periods", "unit", "currency"]


def main():
    acc = json.loads((HERE / "acceptance.json").read_text())
    dev, val = load("dev.json"), load("validation.json")
    first, post = load("heldout_first_run.json"), load("heldout_post_fix.json")
    L = ["# Importer benchmark report", "", f"Extractor {post['extractor_version']}, taxonomy {post['taxonomy_version']}, review threshold {post['threshold']:.0%}.", "",
         "**Read this first.** Every document here is *synthetic*: generated by `benchmarks/fundamentals_importer/generate.py` from invented figures (accounting identities hold exactly) and rendered in the layout, language, number format and",
         "file format of each market. The benchmark measures whether the extractor survives those conventions and wordings. It cannot measure how it behaves on a real filing's own quirks, and **no real filing was part of any split**.",
         "OCR was *simulated* (the true words with random digit errors): the accuracy of a real OCR engine was not measured, because none is installed in the build environment.", "",
         "## Splits and how they were used", "",
         "* **dev** (14 cases): the layouts and wording the rules were written against. Tuned freely.",
         "* **validation** (8 cases): different wording and layouts, checked while developing and then also used to add label names. Tuned.",
         "* **held-out** (24 cases): third wording, layouts and traps (parent-company statements, segment tables, five-year summaries, scans with OCR errors, restated comparatives, wrapped labels, left-aligned figures) written separately.",
         "  It was **run once, unseen** (first run, below) and no label name was ever added from it. Afterwards generic code changes were made, two of them prompted by its failures: (1) the prior-period date of numbered",
         "  terms in half-year income statements, and (2) month names in French, German, Spanish, Portuguese, Italian and Dutch, both found by the held-out run; (3) a confidence cap on the fallback reader and (4) taking the fiscal",
         "  year end from a balance sheet's full dates and trusting a recognised statement over the fallback reader, both found while writing unit tests; and then the whole column / period / currency / candidate / validation redesign of the hardening work",
         "  (`docs/importer_hardening_report.md`), driven by seven *other* reports' failure classes, not by held-out failures (the held-out confident-error regression it caused was found and fixed: Korean numbered terms). The post-fix numbers are therefore *contaminated* by (1) and (2) and are reported",
         "  separately. The files are frozen by `heldout.lock` (a test fails if they change); a fresh held-out batch is needed before any further claim.", "",
         "## Results by split", "", table([metrics_row("dev", dev["summary"]["overall"]), metrics_row("validation", val["summary"]["overall"]), metrics_row("held-out, first run (unseen)", first["summary"]["overall"]),
                                          metrics_row("held-out, after the generic changes (see below)", post["summary"]["overall"])], COLS), "",
         "The gap between dev/validation (100%) and held-out (68%) is the size of the generalisation problem: almost all of the held-out loss is **row labels in wording the label lists did not contain**. Those lines are *not extracted*",
         "(the line is simply absent, and the lines present are right), not extracted wrongly. A line that is absent is a gap a person can see; a wrong value is the dangerous failure, counted separately as *confident errors*.", ""]
    L += ["## Held-out, first run: where the errors were", "", f"{first['summary']['overall']['confident_errors']} confident errors (a wrong or invented value carrying confidence at or above the threshold) in the first run; after the fixes {post['summary']['overall']['confident_errors']}.",
          "The first-run errors came from a Korean half-year report (the prior-period column was dated to the last year end instead of the same half a year earlier) and from a German half-year report whose dates were not read",
          "(German month names) so the fallback reader answered, with no statement context and therefore no confidence.", ""]
    L += ["## By filing format (held-out, after fixes)", "", table([metrics_row(k, v) for k, v in post["summary"]["by_format"].items()], COLS), ""]
    scan = [c for c in post["cases"] if c["scanned"]]
    nscan = [c for c in post["cases"] if not c["scanned"] and c["format"] == "pdf"]
    def agg(cs):
        e = sum(c["expected"] for c in cs)
        return f"{sum(c['correct'] for c in cs) / max(e, 1):.0%} recall, {sum(c['wrong'] for c in cs)} wrong values, {sum(c['confident_errors'] for c in cs)} confident errors, {sum(c['wrong_caught'] for c in cs)} of {sum(c['wrong'] for c in cs)} wrong values caught by low confidence"
    L += ["### Scanned PDFs (simulated OCR with 4% of digit-bearing words damaged)", "", f"* scanned ({len(scan)} cases): {agg(scan)}", f"* text-layer PDFs ({len(nscan)} cases): {agg(nscan)}",
          "* Every wrong value that OCR damage produced was caught: a damaged digit breaks a reconciliation (assets = liabilities + equity, gross profit, net income across statements) or lowers the line's confidence below the threshold, so it is stored unverified.", ""]
    L += ["## By market (held-out, after fixes)", "", table([metrics_row(k, v) for k, v in post["summary"]["by_market"].items()], COLS), "",
          "## By period type", "", table([metrics_row(k, v) for k, v in post["summary"]["by_period_type"].items()], COLS), "",
          "## By layout", "", table([metrics_row(k, v) for k, v in post["summary"]["by_layout"].items()], COLS), ""]
    L += ["## Which (market, format) pairs pass the acceptance criteria", "",
          "Criteria (`acceptance.json`): at least 2 held-out cases; critical-line accuracy ≥ 95%; line recall ≥ 90%; confident-error rate ≤ 0.5%; statements, periods, unit and currency ≥ 95%; ≥ 90% of wrong values caught.", ""]
    rows = []
    groups = {}
    for c in post["cases"]:
        groups.setdefault((c["market"], c["format"] + ("-scan" if c["scanned"] else "")), []).append(c)
    from harness import aggregate
    for (m, f), cs in sorted(groups.items()):
        a = aggregate(cs)["overall"]
        ok, why = passes(a, acc)
        rows.append([m, f, a["cases"], pct(a["recall"]), pct(a["critical_accuracy"]), f"{a['confident_error_rate']:.2%}", "**passes (synthetic held-out)**" if ok else "does not pass: " + "; ".join(why[:3]), "not tested"])
    npass = sum(1 for r in rows if r[6].startswith("**passes"))
    L += [f"**{npass} of {len(rows)} (market, format) pairs pass on the synthetic held-out split; 0 were tested on real filings.**", "",
          table(rows, ["market", "format", "held-out cases", "recall", "critical", "conf. errors", "synthetic held-out", "real filings"]), "",
          "'Not tested' means no real filing of that market and format was run. **No pair is claimed as supported.** Where a pair passes on synthetic documents, that says the layout handling works; it does not say the market's real reports are read correctly.", ""]
    L += ["## Rejection reasons (held-out, after fixes)", "", table([[k, v] for k, v in post["summary"]["rejection_reasons"].items()], ["reason", "count"]), "",
          "## Fallback usage", "", f"{pct(post['summary']['overall']['fallback_rate'])} of held-out cases needed a fallback (the line-by-line reader after the layout engine found fewer than 4 lines).", ""]
    (ROOT / "docs" / "importer_benchmark_report.md").write_text("\n".join(L) + "\n")
    print("written")


if __name__ == "__main__":
    import sys
    sys.path.insert(0, str(HERE))
    main()
