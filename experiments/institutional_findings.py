def _cell(v, floatfmt: str) -> str:
    if isinstance(v, (float, np.floating)):
        if not np.isfinite(v):
            return ""
        if float(v).is_integer() and abs(v) >= 1:
            return str(int(v))
        if abs(v) >= 1e5 or (0 < abs(v) < 1e-3):
            return f"{v:.3g}"
        return floatfmt.format(v)
    return str(v)


def md(frame: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = [frame.index.name or ""] + [str(c) for c in frame.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in frame.iterrows():
        out.append("| " + " | ".join([_cell(idx, floatfmt)] + [_cell(v, floatfmt) for v in row]) + " |")
    return "\n".join(out)


class Report:
    def __init__(self, root: Path):
        self.root, self.parts, self.tables = root, [], {}

    def h(self, title: str, level: int = 2):
        self.parts.append("\n" + "#" * level + " " + title + "\n")

    def p(self, text: str):
        self.parts.append(text + "\n")

    def table(self, name: str, frame: pd.DataFrame, caption: str = "", floatfmt: str = "{:.3f}"):
        self.tables[name] = frame
        if caption:
            self.p(caption)
        self.parts.append(md(frame, floatfmt) + "\n")

    def save(self):
        (self.root / "docs" / "institutional_findings.md").write_text("\n".join(self.parts), encoding="utf-8")
        out = self.root / "reports" / "tables"
        out.mkdir(parents=True, exist_ok=True)
        for name, frame in self.tables.items():
            frame.to_csv(out / f"institutional_{name}.csv")


def guarded(report: Report, title: str):
    def wrap(fn):
        def run(*a, **k):
            t0 = time.perf_counter()
            try:
                fn(*a, **k)
            except Exception as exc:                                    # a failing section is reported, not hidden, and does not stop the others
                report.p(f"*{title}: could not be computed ({type(exc).__name__}: {str(exc)[:150]}).*")
            print(f"{title}: {time.perf_counter() - t0:.0f}s", flush=True)
        return run
    return wrap


