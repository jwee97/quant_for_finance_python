            rows[f"{p:.1%}"] = {"historical VaR": float(np.quantile(loss, p)), "normal VaR": float(sps.norm.ppf(p, loss.mean(), loss.std())), "EVT (GPD) VaR": fit.var(p), "EVT ES": fit.es(p)}
