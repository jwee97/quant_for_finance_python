        rep.table("evt_spy", t, f"**SPY daily loss tail.** GPD fitted above the 95th percentile of losses: shape xi = {fit.xi:.3f} (standard error {fit.xi_se:.3f}), {fit.n_exceed} exceedances. The normal distribution understates the 99.9% loss; the EVT estimate extrapolates beyond what the sample's quantile can.", "{:.4f}")
        dyn = evt.dynamic_evt_var(spy, 0.99, min_obs=1000, refit_every=63)
        ewma = np.sqrt((spy ** 2).ewm(halflife=40, adjust=False).mean()).shift(1)
        normal_var = ewma * sps.norm.ppf(0.99)
        breach_normal = (-spy > normal_var).reindex(dyn.index).dropna()
        kn = len(dyn)
        rows = {"conditional EVT": {"breach rate": float(dyn["breach"].mean()), "Kupiec p": kupiec_test(int(dyn["breach"].sum()), kn, 0.99)[1]},
                "EWMA-normal": {"breach rate": float(breach_normal.mean()), "Kupiec p": kupiec_test(int(breach_normal.sum()), len(breach_normal), 0.99)[1]}}
        rep.table("var_backtest", pd.DataFrame(rows).T, f"**99% one-day VaR backtest on SPY** ({kn} days, target breach rate 1%). Kupiec's p-value tests that the breach rate equals 1%.", "{:.4f}")
        rows = {}
        for other in ("EFA", "TLT", "HYG", "GLD"):
            pair = rets[["SPY", other]].dropna()
            comp = copulas.compare_copulas(pair.to_numpy())
            rows[f"SPY-{other}"] = {"best family (AIC)": comp.index[0], "Spearman": float(pair.corr(method="spearman").iloc[0, 1]), "lower tail dep.": float(comp.loc[comp.index[0], "lower_tail"]),
                                    "upper tail dep.": float(comp.loc[comp.index[0], "upper_tail"]), "Gaussian-vs-best AIC gap": float(comp.loc["gaussian", "aic"] - comp.iloc[0]["aic"])}
        rep.table("copulas", pd.DataFrame(rows).T, "**Copulas for pairs with SPY** (pseudo-observations, daily): best family by AIC, the implied tail dependence and how much worse a Gaussian copula fits (AIC gap).")
        ew = rets.mean(axis=1).dropna()
        sixty = (0.6 * rets["SPY"] + 0.4 * rets["IEF"]).dropna()
        rows = {}
        for name, r in (("SPY", spy), ("60/40 SPY/IEF", sixty), ("equal weight 15 ETFs", ew)):
            d = ruin.drawdown_distribution(r.to_numpy(), 252, 3000, seed=1)
            rows[name] = {"expected max drawdown, 1y": d["mean"], "5th percentile": d["p95"], "1st percentile": d["p99"], "P(drawdown > 20% within 1y)": float((d["mdd"] <= -0.2).mean()),
                          "Kelly leverage (half)": ruin.kelly_from_returns(r.to_numpy(), 0.5)}
        rep.table("drawdown", pd.DataFrame(rows).T, "**One-year maximum-drawdown distribution** by stationary-bootstrap resampling of each series' own daily returns (block length chosen by Politis-White), and the half-Kelly leverage implied by its mean and variance.")
        b = bayesian_sharpe(spy.to_numpy(), 2000)
        cmp = compare_sharpe(spy.to_numpy()[-2500:], ew.to_numpy()[-2500:], 2000)
        rep.p(f"**Bayesian Sharpe ratio of SPY** (Student-t likelihood, MCMC; R-hat <= {float(b['rhat'].max()):.2f}): posterior median {b['median']:.2f}, 95% HPD [{b['hpd95'][0]:.2f}, {b['hpd95'][1]:.2f}], "
              f"P(Sharpe > 0) = {b['prob_positive']:.3f}; fitted tail degrees of freedom {b['nu_median']:.1f} (the sample Sharpe ratio is {spy.mean() / spy.std() * np.sqrt(252):.2f}: with the degrees of freedom this close to 2 the fitted variance is barely finite and the model's Sharpe ratio is not the sample one, so read the interval as a statement of how uncertain the mean is, not as a better point estimate). SPY against the equal-weight book over the last 2,500 days: P(SPY better) = {cmp['prob_a_better']:.2f}.")

