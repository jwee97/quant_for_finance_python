    @guarded(rep, "statistics")
    def statistics():
        from src.stats import adf_test, engle_granger, fama_macbeth, granger_causality, hurst_exponent, kpss_test, p_adjust, variance_ratio
        from src.econometrics import johansen

        rep.h("1. Statistics on the 15 ETFs (real data)")
        rows = {}
        for a in ["SPY", "TLT", "GLD", "HYG"]:
            lp = np.log(prices[a].dropna())
            r = lp.diff().dropna()
            rows[a] = {"ADF p (log price)": adf_test(lp.to_numpy(), "c").pvalue, "KPSS p (log price)": kpss_test(lp.to_numpy(), "c").pvalue, "ADF p (returns)": adf_test(r.to_numpy(), "c").pvalue,
                       "VR(5) robust z": variance_ratio(prices[a].dropna(), 5)["z_robust"], "VR(21) robust z": variance_ratio(prices[a].dropna(), 21)["z_robust"], "Hurst (R/S)": hurst_exponent(r.to_numpy())}
        rep.table("stationarity", pd.DataFrame(rows).T, "**Unit roots, variance ratios and Hurst.** Prices are unit-root processes (ADF does not reject, KPSS rejects) and returns are stationary, as expected; the variance ratios and Hurst exponents show how little linear predictability daily ETF returns carry.")
        pairs = [("EEM", "EFA"), ("GLD", "SLV"), ("IEF", "TLT"), ("LQD", "HYG"), ("SPY", "QQQ"), ("IWM", "SPY")]
        rows = {}
        for y, x in pairs:
            ly, lx = np.log(prices[y]).dropna(), np.log(prices[x]).dropna()
            both = pd.concat([ly, lx], axis=1).dropna()
            eg = engle_granger(both.iloc[:, 0], both.iloc[:, 1], maxlag=5, autolag=None)
            jo = johansen(both, 1, 0)
            rows[f"{y}/{x}"] = {"hedge ratio": float(eg["hedge_ratio"].iloc[-1]), "EG p": eg["pvalue"], "half-life (days)": eg["half_life"], "Johansen rank (5%)": jo["rank"]}
        rep.table("cointegration", pd.DataFrame(rows).T, "**Cointegration of the pairs the stat-arb strategies trade, full sample.** Full-sample tests flatter pairs trading: the relationship has to be estimated in real time, which `cointegration_pairs` does with a rolling window.")
        rr = rets[["SPY", "QQQ", "IWM", "EFA", "EEM", "TLT", "IEF", "HYG", "LQD", "GLD", "DBC", "VNQ"]].dropna()
        target = "SPY"
        others = [c for c in rr.columns if c != target]
        gp = {}
        for c in others:
            g = granger_causality(rr[target], rr[c], 3)
            gp[c] = float(g["pvalue"].min())
        adj = p_adjust(np.array(list(gp.values())), "bh")
        rep.table("granger", pd.DataFrame({"min p over 1-3 lags": gp, "BH-adjusted": dict(zip(gp, adj))}), "**Does anything Granger-cause SPY's daily return?** Smallest p-value over lags 1 to 3 for each other ETF, and the Benjamini-Hochberg adjusted value (11 tests). Several ETFs hold foreign or illiquid assets whose prices are stale at the US close, so a lagged return can carry same-day US information: statistical significance here is about non-synchronous prices, and is not evidence of a tradable lead.")
        monthly = prices.resample("ME").last().pct_change()
        mom = (prices.resample("ME").last().pct_change(11).shift(1))
        rev = prices.resample("ME").last().pct_change().shift(1)
        vol = rets.rolling(63).std().resample("ME").last().shift(1)
        fm = fama_macbeth(monthly.iloc[13:], {"mom_2_12": mom.iloc[13:], "reversal_1m": rev.iloc[13:], "vol_63d": vol.iloc[13:]}, lag=0, min_assets=10)
        rep.table("fama_macbeth", fm.summary(), f"**Fama-MacBeth** monthly cross-sectional regressions of next-month returns on lagged characteristics ({fm.n_periods} months, on average {fm.avg_assets:.0f} ETFs, Newey-West {fm.lags} lags). With 15 assets the standard errors are wide and the asset-class structure dominates the cross-section.")

