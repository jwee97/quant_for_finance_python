"""Figures from a spreadsheet: a CSV or tab-separated file, or an Excel workbook (.xlsx).

The reading of the table itself is the one the Enter-reports grid already uses (:func:`manual.parse_table`: periods across the top or down the side, line names recognised against the canonical lines),
so a file imported here and the same table pasted there give the same figures. An Excel workbook is turned into text first, one sheet at a time, and the sheet that holds the most recognised lines is
used; the others are listed. Cells that are formulas are read as the value Excel last saved (``data_only``): a workbook that was never opened in Excel after being generated by a script has none, and is
refused with that reason, never read as zero.
"""

from __future__ import annotations

import io
import re

from .. import manual
from ..errors import FundamentalsError

UNIT_WORDS = (("billions", r"in\s+billions|\$\s*billions|\(\s*billions|十億円|십억원|十亿|单位[:：]?\s*亿"),
              ("millions", r"in\s+millions|\$\s*millions|\(\s*millions|\bmillions of\b|百万円|百萬円|백만원|百万元|百萬元|百万|en millones|in millionen|em milhões|milhões de"),
              ("thousands", r"in\s+thousands|\$\s*thousands|\(\s*thousands|\bthousands of\b|000s|千円|천원|千元|单位[:：]?\s*千|en miles|in tausend|em milhares|milhares de"))


def detect_units(text: str) -> str | None:
    """The unit a statement says its amounts are in ("in thousands", "$ millions"), or None when it says nothing."""
    low = (text or "")[:8000].lower()
    for unit, pattern in UNIT_WORDS:
        if re.search(pattern, low):
            return unit
    return None


def decode(data: bytes) -> str:
    for enc in ("utf-8-sig", "utf-16", "cp1252", "latin-1"):
        try:
            return data.decode(enc)
        except (UnicodeDecodeError, UnicodeError):
            continue
    return data.decode("utf-8", errors="replace")


def _draft(parsed: dict, method: str, notes: list[str], units: str | None, source_ref: dict | None = None) -> dict:
    cols = parsed["columns"]
    periods = []
    for j, c in enumerate(cols):
        values, sources = {}, {}
        for code, row in parsed["values"].items():
            v = row[j] if j < len(row) else None
            if v is not None:
                values[code] = v
                sources[code] = {"tag": None, "reported": v, "unit": units or "units", "method": method, **(source_ref or {})}
        if values:
            periods.append({"fiscal_period": c.get("fiscal_period") or "FY", "period_end": c.get("period_end"), "fiscal_year": c.get("fiscal_year"), "filing_date": c.get("filing_date"),
                            "currency": c.get("currency"), "values": values, "sources": sources, "label": c.get("label"), "guessed": bool(c.get("guessed"))})
    if not periods:
        raise FundamentalsError("the table has no figures for any line this application knows")
    return {"periods": periods, "units": {"money": units or "units", "shares": "units"}, "currency": None, "company": {}, "notes": notes + list(parsed.get("notes") or []), "ytd_only": [],
            "unmapped": [u["label"] for u in parsed.get("unrecognised", [])][:60], "method": method, "problems": parsed.get("problems", []), "units_stated": units is not None, "accession": None}


def from_text(text: str, method: str = "csv", ref: dict | None = None) -> dict:
    units = detect_units(text)
    parsed = manual.parse_table(text.replace("\r\n", "\n"))
    notes = [] if units else ["The file does not say whether its amounts are in units, thousands or millions: they are read as units. Choose the unit below if they are not."]
    return _draft(parsed, method, notes, units, ref)


def from_xlsx(data: bytes) -> dict:
    try:
        import openpyxl
    except ImportError:
        raise FundamentalsError("reading an Excel workbook needs the openpyxl package (pip install openpyxl); a CSV export of the sheet can be imported without it") from None
    try:
        wb = openpyxl.load_workbook(io.BytesIO(data), data_only=True, read_only=True)
    except Exception as error:                                                                    # a corrupt or password-protected workbook
        raise FundamentalsError(f"this workbook could not be opened ({type(error).__name__}): is it password-protected or damaged?") from None
    best, best_hits, listed = None, -1, []
    for ws in wb.worksheets:
        rows = []
        for row in ws.iter_rows(values_only=True):
            cells = ["" if c is None else (c.strftime("%Y-%m-%d") if hasattr(c, "strftime") else str(c)) for c in row]
            if any(x.strip() for x in cells):
                rows.append("\t".join(cells))
            if len(rows) > manual.MAX_ROWS + 20:
                break
        text = "\n".join(rows)
        try:
            parsed = manual.parse_table(text)
            hits = len(parsed["values"])
        except FundamentalsError:
            hits, parsed = 0, None
        listed.append(f"{ws.title} ({hits} recognised lines)")
        if parsed is not None and hits > best_hits:
            best, best_hits, best_text, best_title = parsed, hits, text, ws.title
    if best is None:
        raise FundamentalsError("no sheet of the workbook is a table of periods and known lines (sheets: " + "; ".join(listed) + "). Formula cells that Excel never calculated read as empty.")
    units = detect_units(best_text)
    notes = [f"Read the sheet '{best_title}' (of {len(listed)}: " + "; ".join(listed) + ")."]
    if not units:
        notes.append("The sheet does not say whether its amounts are in units, thousands or millions: they are read as units. Choose the unit below if they are not.")
    return _draft(best, "xlsx", notes, units, {"sheet": best_title})
