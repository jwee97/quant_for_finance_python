"""What the options, futures and crypto workspaces share: the snapshot every asset class reduces to, where each number came from, and the small statistics they all use.

**Provenance is part of the data.** The repository holds no option chains, futures contracts or multi-venue crypto quotes of its own, so a workspace is built from four kinds of input and every
payload says which it used (``source`` and, per part, ``sources``):

``platform``     real data the repository holds: ETF prices, the Deribit BTC and ETH perpetual and funding history, the DefiLlama stablecoin supply, the VIX-family implied-volatility indices
``user_file``    a file you put in ``data/user/`` (an option chain, a futures curve, a crypto history)
``downloaded``   real data the platform fetched for you from a free public source (``assets.free_data``: Cboe, Yahoo Finance, Deribit, Coinbase, Kraken, Bitstamp, OKX), saved under
                 ``data/user/downloads/`` with a record of where and when; delayed or unaudited, and labelled with its source
``simulated``    generated by a model or a random generator (the SSVI option chain anchored to a real spot and volatility, Schwartz-Smith futures curves, the venues other than Deribit, the order book)
``mixed``        some parts real and some simulated: the part-by-part ``sources`` mapping says which

A page that shows a simulated number as if it were a market quote would mislead, so the dashboard prints the source above every table and the analytics here refuse to hide it.
"""

from __future__ import annotations

import math
from dataclasses import asdict, dataclass, field

import numpy as np
import pandas as pd

SOURCES = ("platform", "user_file", "downloaded", "simulated", "mixed")
TRADING_DAYS = 252.0


@dataclass
class AssetSnapshot:
    """One line about one instrument, the same for options, futures and crypto: what it trades at, how much it moves, how easy it is to trade and what to watch."""

    symbol: str
    asset_class: str                                  # "option" | "future" | "crypto"
    price: float
    volatility: float                                 # annualised, decimal
    liquidity_score: float                            # 0 (untradable) .. 100 (very liquid)
    risk_flags: list[str] = field(default_factory=list)
    as_of: str | None = None
    source: str = "platform"

    def to_dict(self) -> dict:
        return asdict(self)


def overall_source(parts: dict[str, str]) -> str:
    """The one word for a payload made of several parts: the common source when all parts agree, else ``mixed``."""
    kinds = {v for v in parts.values() if v}
    bad = kinds - set(SOURCES) - {"model"}
    if bad:
        raise ValueError(f"unknown source {sorted(bad)}; choose from {SOURCES}")
    kinds = {"simulated" if k == "model" else k for k in kinds}
    if not kinds:
        return "simulated"
    return kinds.pop() if len(kinds) == 1 else "mixed"


def envelope(kind: str, data: dict, parts: dict[str, str], warnings: list[str] | None = None, as_of=None, notes: list[str] | None = None) -> dict:
    """A payload with its provenance: ``kind``, ``source``, ``sources`` (per part), ``warnings`` (things the reader must know) and ``notes`` (how it was made). ``data`` keys come first-class."""
    out = {"kind": kind, "source": overall_source(parts), "sources": dict(parts), "warnings": list(warnings or []), "notes": list(notes or []),
           "as_of": None if as_of is None else str(pd.Timestamp(as_of).date())}
    clash = set(out) & set(data)
    if clash:
        raise ValueError(f"payload keys {sorted(clash)} are reserved for provenance")
    out.update(data)
    return out


# ------------------------------------------------------------------------------------------------------------------ statistics
def realized_vol(prices: pd.Series, window: int = 21, periods: float = TRADING_DAYS) -> pd.Series:
    """Annualised standard deviation of log returns over a trailing ``window`` (NaN until the window is full)."""
    if window < 2:
        raise ValueError("window must be at least 2")
    return np.log(prices.astype(float)).diff().rolling(window, min_periods=window).std(ddof=1) * math.sqrt(periods)


def percentile_rank(history: pd.Series | np.ndarray, value: float) -> float:
    """The share of the history at or below ``value``, in [0, 1] (NaN for an empty history): the *percentile* of an implied-volatility level."""
    h = np.asarray(history, dtype=float)
    h = h[np.isfinite(h)]
    return float((h <= value).mean()) if len(h) and np.isfinite(value) else float("nan")


def range_rank(history: pd.Series | np.ndarray, value: float) -> float:
    """Where ``value`` sits between the lowest and highest of the history, in [0, 1]: the *rank* (IV rank) as traders use the word. NaN when the history has no range."""
    h = np.asarray(history, dtype=float)
    h = h[np.isfinite(h)]
    if len(h) < 2 or not np.isfinite(value):
        return float("nan")
    lo, hi = float(h.min()), float(h.max())
    return float(np.clip((value - lo) / (hi - lo), 0.0, 1.0)) if hi > lo else float("nan")


def last_zscore(series: pd.Series, window: int = 90) -> float:
    """The last value of ``series`` in standard deviations of its trailing ``window`` (the last value included); NaN when the window has no spread."""
    s = series.dropna().tail(window)
    if len(s) < 5:
        return float("nan")
    sd = float(s.std(ddof=1))
    return float((s.iloc[-1] - s.mean()) / sd) if sd > 0 else float("nan")


def liquidity_score(spread_bps: float, dollar_volume: float) -> float:
    """A 0-100 score from how wide the market is and how much trades in it: half from the spread (``1 / (1 + spread_bps / 10)``, 100 at a zero spread) and half from the dollar volume
    (zero at $10 thousand a day, 100 at $1 billion and above). A convention for ranking, not a measurement of market impact."""
    spread_part = 1.0 / (1.0 + max(float(spread_bps), 0.0) / 10.0) if np.isfinite(spread_bps) else 0.0
    volume_part = float(np.clip((math.log10(max(float(dollar_volume), 1.0)) - 4.0) / 5.0, 0.0, 1.0)) if np.isfinite(dollar_volume) else 0.0
    return round(100.0 * (0.5 * spread_part + 0.5 * volume_part), 1)


def drawdown(prices: pd.Series) -> float:
    """The latest fall from the running peak, as a negative fraction."""
    p = prices.dropna()
    return float(p.iloc[-1] / p.cummax().iloc[-1] - 1.0) if len(p) else float("nan")


def nice_step(x: float) -> float:
    """A round strike or price increment near ``x``: 1, 2, 2.5 or 5 times a power of ten."""
    if not np.isfinite(x) or x <= 0:
        raise ValueError("step must be positive")
    exp = math.floor(math.log10(x))
    for m in (1.0, 2.0, 2.5, 5.0, 10.0):
        if m * 10 ** exp >= x * 0.999:
            return float(m * 10 ** exp)
    return float(10 ** (exp + 1))


def add_flag(flags: list[str], condition: bool, message: str) -> None:
    """Append ``message`` to ``flags`` when ``condition`` holds (keeps the flag lists in the analytics free of ``if`` clutter)."""
    if condition:
        flags.append(message)


def json_series(index, values, digits: int = 6) -> list:
    """Values rounded for a JSON payload; non-finite numbers become ``None``."""
    return [None if not np.isfinite(v) else round(float(v), digits) for v in np.asarray(values, dtype=float)]


def date_strings(index) -> list[str]:
    return [str(pd.Timestamp(d).date()) for d in index]
